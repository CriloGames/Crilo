create or replace function ascent_game.match_guess(dictionary_version integer, clues text[], answer text) returns jsonb language plpgsql stable set search_path='' as $fn$
declare candidates text[]; alternate text; simplified text; links jsonb:='{}'; fallback text[];
begin
 if length(coalesce(answer,''))>120 then return links;end if;
 answer:=lower(btrim(regexp_replace(regexp_replace(coalesce(answer,''),'[’'']','', 'g'),'[[:space:]‐‑–—-]+',' ','g')));
 answer:=btrim(regexp_replace(answer,'[.!?]+$','','g'));
 if answer !~ '^[a-z0-9]+( [a-z0-9]+){0,15}$' or answer=any(clues) then return links; end if;
 candidates:=array[answer];
 if length(answer)>3 and right(answer,3)='ies' then candidates:=array_append(candidates,left(answer,-3)||'y');end if;
 if answer ~ '(ch|sh|s|x|z)es$' then candidates:=array_append(candidates,left(answer,-2));end if;
 if length(answer)>2 and right(answer,1)='s' and right(answer,2)<>'ss' then candidates:=array_append(candidates,left(answer,-1));end if;
 -- Preserve existing registered answer scores; only use aliases/phrase normalization when no exact answer matched.
 select coalesce(jsonb_object_agg(x.clue,x.reason),'{}') into links from (
  select distinct on (c.clue) c.clue,c.reason from (
   select l.clue,100 strength,e.value reason from ascent_game.circuit_lexicon l cross join lateral jsonb_each_text(l.links) e where l.edition=dictionary_version and l.clue=any(clues) and e.key=any(candidates) and e.key<>all(clues) and dictionary_version<>7
   union all
   select s.clue,s.strength,s.reason||' ('||s.strength||'% match)' from ascent_game.association_scores_v7 s where dictionary_version in (6,7) and s.clue=any(clues) and s.word=any(candidates) and s.word<>all(clues) and s.strength>=65
  ) c order by c.clue,c.strength desc,c.reason
 ) x;
 if links<>'{}'::jsonb or dictionary_version not in (6,7) then return links;end if;
 simplified:=btrim(regexp_replace(regexp_replace(answer,'^(something to do with|related to|the idea of|the concept of|a type of|a kind of) +','','i'),'\m(a|an|the)\M *','','g'));
 simplified:=regexp_replace(simplified,' +',' ','g');

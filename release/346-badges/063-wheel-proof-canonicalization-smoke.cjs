'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const sql=fs.readFileSync('release/346-badges/063-wheel-proof-canonicalization.sql','utf8');
const game=fs.readFileSync('game.js','utf8');
const sections=sql.split(/CREATE OR REPLACE FUNCTION public\./);
const run=sections.find(s=>s.startsWith('enforce_crilo_run_mode('));
const proof=sections.find(s=>s.startsWith('crilo_verify_attached_spin_session('));
assert.ok(run&&proof);
assert.match(run,/new\.is_test := false/,'Force official records');
assert.match(run,/if v_has_official_run then[\s\S]*raise exception/,'Reject second owner/regular Daily');
assert.doesNotMatch(run,/new\.is_test := true/,'No test records in official table');
assert.match(proof,/user_id=NEW\.user_id FOR UPDATE/,'Lock only owned proof');
assert.match(proof,/s\.finished_at IS NULL OR s\.remaining_spins<>0/,'Proof must be complete');
assert.match(proof,/s\.daily_period IS DISTINCT FROM NEW\.daily_period/,'Proof belongs to correct reset');
assert.match(proof,/NEW\.results := s\.results/,'Store canonical server outcomes');
assert.match(proof,/NEW\.rarity_score := NEW\.rarity_score \* /,'Canonical odds');
assert.match(proof,/INTO NEW\.best_roll_points,NEW\.best_roll_label/,'Canonical high roll');
assert.match(game,/verified_spin_session_id:serverSessionId/,'Official game submits proof');
assert.match(game,/crilo_save_owner_test_run/,'Owner Test Run uses separate storage');
console.log('PASS: no owner test injection into official leaderboard, canonical score proof/rarity/high-roll evidence.');

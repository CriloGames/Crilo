'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const js=fs.readFileSync('game.js','utf8');
const css=fs.readFileSync('center-drawing-modes.css','utf8');
const a=html.match(/<select id="drawMode"[^>]*>(.*?)<\/select>/);
const b=html.match(/<select id="pixelDrawMode"[^>]*>(.*?)<\/select>/);
assert.ok(a&&b,'Both editors must have the drawing-center dropdown');
const options=s=>[...s.matchAll(/<option value="([^"]+)">([^<]+)<\/option>/g)].map(x=>[x[1],x[2]]);
assert.deepEqual(options(a[1]),options(b[1]),'Exact option labels and values must match');
assert.deepEqual(options(a[1]),[['stationary','Center stays still'],['spin','Center spins']]);
assert.match(a[0],/class="center-drawing-spin-select"/);
assert.match(b[0],/class="center-drawing-spin-select"/);
assert.match(js,/\$\('drawMode'\)\.onchange=e=>setCenterDrawingSpinMode\(e\.target\.value\)/);
assert.match(js,/\$\('pixelDrawMode'\)\.onchange=e=>setCenterDrawingSpinMode\(e\.target\.value\)/);
assert.match(js,/\$\('drawMode'\)\.value=mode;/);
assert.match(js,/\$\('pixelDrawMode'\)\.value=mode;/);
assert.match(js,/setCenterDrawingSpinMode\(previous\.drawMode\)/,'Guest restore must sync BOTH controls');
assert.match(js,/setCenterDrawingSpinMode\(\$\('pixelDrawMode'\)\.value\)/,'Closing Studio must keep saved mode');
assert.match(html,/center-drawing-modes\.css\?v=\d+/);
assert.match(css,/html\[data-theme="dark"\]/);
assert.match(css,/max-width:700px/);
assert.match(css,/font-size:16px/);
console.log('CENTER_MODE_PARITY_SMOKE_PASS labels, values, two-way synchronization, restore, responsive formatting');
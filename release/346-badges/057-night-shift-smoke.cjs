/* Crilo's support page is now an intentionally simple pastel tip page.
   Regression verifies that no game mechanics or sign-in gate remain. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..');
const html=fs.readFileSync(path.join(root,'support.html'),'utf8');
const css=fs.readFileSync(path.join(root,'support-pastel.css'),'utf8');
const js=fs.readFileSync(path.join(root,'support-pastel.js'),'utf8');
const music=fs.readFileSync(path.join(root,'shape-of-sound.html'),'utf8');
assert.match(html,/id="supportPayLink"/);
assert.match(html,/id="shapeCanvas"/);
assert.match(html,/class="tip-card"/);
assert.equal((html.match(/id="supportPayLink"/g)||[]).length,1);
assert.equal((html.match(/data-amount="/g)||[]).length,4);
assert.ok(!html.includes('id="nightShift"')&&!html.includes('id="soundStage"'),'Old games must be removed from tip page');
assert.ok(!html.includes('id="accountBtn"')&&!html.includes('app.js'),'No sign-in or account UI');
assert.ok(html.includes('support-pastel.css?v=4')&&html.includes('support-pastel.js?v=3'));
assert.ok(html.includes('family=Manrope'), 'Use the modern Manrope font on the tip page');
assert.ok(css.includes('font-family:"Manrope"'), 'Manrope must be used with a safe system fallback');
assert.ok(css.includes('font-weight:800;font-size:clamp(39px,6.1vw,67px)'), 'Modern headline weight');
assert.ok(css.includes('.tip-card h1 span{display:block;color:#9b78b0')&&!css.includes('3px 5px 0 #d7b7df50'), 'Remove cartoon-style headline shadows');
assert.ok(css.includes('.wall-course')&&css.includes('.shape.brick'),'Must render staggered masonry courses');
assert.ok(css.includes('.brick-mark.wheel')&&css.includes('.brick-mark.duck')&&css.includes('.brick-mark.domain'),'Preserve small Crilo motifs');
assert.ok(js.includes('for(let y=')&&js.includes('field.replaceChildren(fragment)'),'Responsive full-wall masonry, not random confetti');
assert.ok(js.includes('ResizeObserver')&&js.includes('rowHeight'),'Reflow stacked wall when the viewport changes');
assert.ok(!css.includes('@keyframes drift'),'Pastel stones must remain stationary');
assert.ok(css.includes('@media(max-width:650px)')&&css.includes('prefers-reduced-motion:reduce'),'Responsive reduced-motion art');
assert.ok(js.includes('const palette=')&&js.includes('const base='),'Colorful, sizeable pastel stone slabs');
assert.ok(!/fetch\(|\.rpc\(|supabase|paypal\.com|window\.open|location\.href/i.test(js),'Decorations must remain entirely offline');
assert.ok(music.includes('id="soundStage"')&&!music.includes('supportPayLink'),'Music game stays standalone');
assert.ok(html.includes("location.hash==='#shape-of-sound'"),'Previously shared music links must keep working');
console.log('PASS: Tip page has one optional PayPal checkout, interlocking pastel stone wall, no account or other game.');

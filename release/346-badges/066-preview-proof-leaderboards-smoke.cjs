'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const s=fs.readFileSync('leaderboard.js','utf8');
const html=fs.readFileSync('leaderboard.html','utf8');
assert.match(html,/leaderboard\.js\?v=45/,'Load newest competitive-score filter');
assert.match(s,/verified_spin_session_id/,'Discriminate server-proof from old preview');
assert.match(s,/!isLegacyPreviewRun\(run\)/,'Apply filter to single-run leaderboard');
assert.match(s,/if\(isLegacyPreviewRun\(run\)\)continue/,'Apply filter to ducks scoreboard');
const start=s.indexOf('function isLegacyPreviewRun(run){'),stop=s.indexOf('\n}',start);
assert.ok(start>=0&&stop>start);
const extract=s.slice(start,stop+2)+';globalThis.filter=isLegacyPreviewRun;';
const testContext={};vm.runInNewContext(extract,testContext);
const make=(score,spins,upgrades,doubles,ducks,verified=null,date='2026-10-07')=>({score,spins,upgrades,doubles,ducks,verified_spin_session_id:verified,daily_period:date});
assert.equal(testContext.filter(make(864,11,3,1,0)),true,'Legacy 864 excluded');
assert.equal(testContext.filter(make(15,8,0,1,2)),true,'Legacy 15 excluded');
assert.equal(testContext.filter(make(864,11,3,1,0,'verified-session')),false,'Genuine server-proof score retained');
assert.equal(testContext.filter(make(864,11,3,1,0,null,'2026-10-11')),false,'New runs unaffected');
assert.equal(testContext.filter(make(17,7,0,0,2)),false,'Normal Daily retained');
console.log('PASS: same preview exclusion on score and duck boards; new verified scores remain eligible.');
